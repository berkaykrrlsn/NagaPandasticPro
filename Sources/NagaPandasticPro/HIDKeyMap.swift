    ]

    private static var cache: [UInt16: String] = [:]

    static func name(forKeyCode code: UInt16) -> String {
        if let s = special[code] { return s }
        if Thread.isMainThread {
            if let c = cache[code] { return c }
            if let s = layoutCharacter(for: code) {
                cache[code] = s
                return s
            }
        }
        return usFallback[code] ?? "Tuş \(code)"
    }

    /// Klavye düzeni değişince önbelleği temizle
    static func resetCache() { cache.removeAll() }

    /// Geçerli klavye düzenine göre (ör. Türkçe Q) tuşun karakteri
    private static func layoutCharacter(for keyCode: UInt16) -> String? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue()
        guard let bytes = CFDataGetBytePtr(data) else { return nil }
        let layout = UnsafeRawPointer(bytes).assumingMemoryBound(to: UCKeyboardLayout.self)
        var deadKeyState: UInt32 = 0
        let maxLength = 4
        var chars = [UniChar](repeating: 0, count: maxLength)
        var length = 0
        let status = UCKeyTranslate(layout,
                                    keyCode,
                                    UInt16(kUCKeyActionDisplay),
                                    0,
                                    UInt32(LMGetKbdType()),
                                    OptionBits(kUCKeyTranslateNoDeadKeysMask),
                                    &deadKeyState,
                                    maxLength,
                                    &length,
                                    &chars)
        guard status == noErr, length > 0 else { return nil }
        let s = String(utf16CodeUnits: chars, count: length).trimmingCharacters(in: .whitespacesAndNewlines)
        return s.isEmpty ? nil : s.uppercased(with: Locale(identifier: "tr_TR"))
    }

